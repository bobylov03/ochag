const I18nContext = React.createContext({ lang: 'ru', setLang: () => {}, t: (k) => k });

function I18nProvider({ children }) {
  const [lang, setLang] = React.useState(() => {
    try { return localStorage.getItem('ochag_lang') || 'ru'; } catch (e) { return 'ru'; }
  });
  React.useEffect(() => {
    try { localStorage.setItem('ochag_lang', lang); } catch (e) {}
    document.documentElement.lang = lang === 'ge' ? 'ka' : lang;
  }, [lang]);
  const t = React.useCallback((key) => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.ru;
    return dict[key] || TRANSLATIONS.ru[key] || key;
  }, [lang]);
  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

function useI18n() { return React.useContext(I18nContext); }

Object.assign(window, { I18nContext, I18nProvider, useI18n, TRANSLATIONS });
